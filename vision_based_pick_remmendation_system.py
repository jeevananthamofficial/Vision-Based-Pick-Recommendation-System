def identify_product_from_image(
    image,
    top_k=5
):

    product_names = (
        product_catalog["Product_Name"]
        .tolist()
    )

    labels = [
        f"a photo of {name}"
        for name in product_names
    ]

    inputs = vision_processor(
        text=labels,
        images=image,
        return_tensors="pt",
        padding=True
    )

    inputs = {
        k: v.to(device)
        for k, v in inputs.items()
    }

    with torch.no_grad():

        outputs = vision_model(
            **inputs
        )

    logits = outputs.logits_per_image

    probabilities = (
        logits.softmax(dim=1)
        .cpu()
        .numpy()[0]
    )

    top_indices = np.argsort(
        probabilities
    )[::-1][:top_k]

    results = []

    for idx in top_indices:

        row = product_catalog.iloc[idx]

        results.append({

            "Product_ID":
                str(row["Product_ID"]),

            "Product_Name":
                str(row["Product_Name"]),

            "Category":
                str(row["Category"]),

            "score":
                float(probabilities[idx])
        })

    return results


