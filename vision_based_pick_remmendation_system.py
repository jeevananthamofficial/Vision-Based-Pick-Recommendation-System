def detect_with_yolo(pil_image):

    processed = preprocess_image_opencv(
        pil_image
    )

    results = yolo_model.predict(
        source=processed,
        conf=0.25,
        iou=0.45,
        verbose=False
    )

    result = results[0]

    detections = []

    if result.boxes is None:
        return detections

    for box in result.boxes:

        class_id = int(
            box.cls[0].item()
        )

        confidence = float(
            box.conf[0].item()
        )

        xyxy = (
            box.xyxy[0]
            .cpu()
            .numpy()
        )

        detections.append({

            "class_id": class_id,

            "class_name": yolo_model.names[class_id],

            "confidence": confidence,

            "bbox": [
                float(x)
                for x in xyxy
            ]
        })

    return detections


