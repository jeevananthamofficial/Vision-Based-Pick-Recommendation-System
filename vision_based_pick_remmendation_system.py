# 12. YOLO PRODUCT CROP
# ============================================================

def get_yolo_product_crop(
    pil_image,
    confidence_threshold=0.25
):

    results = yolo_model.predict(
        source=np.array(pil_image),
        conf=confidence_threshold,
        iou=0.45,
        verbose=False
    )

    result = results[0]

    if (
        result.boxes is None
        or len(result.boxes) == 0
    ):
        return None, []

    detections = []

    best_box = None
    best_confidence = 0

    for box in result.boxes:

        class_id = int(
            box.cls[0].item()
        )

        confidence = float(
            box.conf[0].item()
        )

        xyxy = (
            box.xyxy[0]
            .cpu()
            .numpy()
        )

        detection = {

            "class_id": class_id,

            "class_name":
                yolo_model.names[class_id],

            "confidence":
                confidence,

            "bbox":
                [float(x) for x in xyxy]
        }

        detections.append(
            detection
        )

        if confidence > best_confidence:

            best_confidence = confidence
            best_box = xyxy

    if best_box is None:
        return None, detections

    x1, y1, x2, y2 = map(
        int,
        best_box
    )

    width, height = pil_image.size

    x1 = max(
        0,
        min(x1, width)
    )

    x2 = max(
        0,
        min(x2, width)
    )

    y1 = max(
        0,
        min(y1, height)
    )

    y2 = max(
        0,
        min(y2, height)
    )

    if (
        x2 <= x1
        or y2 <= y1
    ):
        return None, detections

    cropped_image = pil_image.crop(
        (x1, y1, x2, y2)
    )

    return (
        cropped_image,
        detections
    )


