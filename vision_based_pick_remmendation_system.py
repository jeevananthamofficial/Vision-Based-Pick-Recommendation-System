def generate_recommendations(
    detected_product,
    rag_products,
    number_of_recommendations=5
):

    candidate_text = "\n".join([

        f"""
Product_ID: {p['Product_ID']}
Product_Name: {p['Product_Name']}
Category: {p['Category']}
RAG_Score: {p['rag_score']:.4f}
""".strip()

        for p in rag_products
    ])

    prompt = f"""
You are a product recommendation engine.

Detected product:

Product_ID:
{detected_product['Product_ID']}

Product_Name:
{detected_product['Product_Name']}

Category:
{detected_product['Category']}

RAG candidate products:

{candidate_text}

Task:

Recommend exactly
{number_of_recommendations}
products.

Rules:

1. Do NOT recommend the detected product.
2. Use ONLY the RAG candidate products.
3. Do NOT invent products.
4. Do NOT invent Product_IDs.
5. Preserve Product_ID exactly.
6. Preserve Product_Name exactly.
7. Prefer complementary or useful products.
8. Return JSON only.

Required format:

{{
  "recommendations": [
    {{
      "Product_ID": "P00000",
      "Product_Name": "Exact Product Name"
    }}
  ]
}}
"""

    interaction = client.interactions.create(
        model="gemini-3.6-flash",
        input=prompt
    )

    text = interaction.output_text.strip()

    # Remove markdown code fences
    text = re.sub(
        r"^```json\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"\s*```$",
        "",
        text
    )

    data = json.loads(text)

    valid_products = {
        p["Product_ID"]:
            p["Product_Name"]

        for p in rag_products
    }

    detected_id = (
        detected_product["Product_ID"]
    )

    final_recommendations = []

    for item in data.get(
        "recommendations",
        []
    ):

        product_id = str(
            item.get(
                "Product_ID",
                ""
            )
        ).strip()

        if product_id not in valid_products:
            continue

        if product_id == detected_id:
            continue

        final_recommendations.append({

            "Product_ID":
                product_id,

            "Product_Name":
                valid_products[
                    product_id
                ]
        })

    # Remove duplicates
    unique = {}

    for item in final_recommendations:

        unique[
            item["Product_ID"]
        ] = item

    return {
        "recommendations":
            list(unique.values())[
                :number_of_recommendations
            ]
    }


