# 18. COMPLETE AI PIPELINE
# ============================================================

def final_warehouse_pipeline(
    pil_image,
    top_k_vision=5,
    top_k_rag=10
):

    # -----------------------------------
    # STEP A — YOLO DETECTION
    # -----------------------------------

    product_crop, yolo_detections = (
        get_yolo_product_crop(
            pil_image
        )
    )

    if product_crop is None:

        return {

            "status": "failed",

            "stage": "YOLO",

            "message":
                "YOLO could not detect a product.",

            "yolo_detections":
                []
        }

    # -----------------------------------
    # STEP B — PRODUCT IDENTIFICATION
    # -----------------------------------

    vision_results = (
        identify_product_from_image(
            product_crop,
            top_k=top_k_vision
        )
    )

    if not vision_results:

        return {

            "status": "failed",

            "stage": "VISION",

            "message":
                "Product identification failed.",

            "yolo_detections":
                yolo_detections
        }

    detected_product = (
        vision_results[0]
    )

    # -----------------------------------
    # STEP C — TEXT RAG
    # -----------------------------------

    rag_query = (
        f"{detected_product['Product_Name']} "
        f"{detected_product['Category']}"
    )

    rag_products = retrieve_products(
        rag_query,
        top_k=top_k_rag
    )

    # Remove detected product
    rag_products = [
        p
        for p in rag_products
        if p["Product_ID"]
        != detected_product["Product_ID"]
    ]

    # -----------------------------------
    # STEP D — GEMINI RECOMMENDATION
    # -----------------------------------

    recommendation_result = (
        generate_recommendations(
            detected_product=
                detected_product,

            rag_products=
                rag_products,

            number_of_recommendations=5
        )
    )

    recommendations = (
        recommendation_result
        .get(
            "recommendations",
            []
        )
    )

    # -----------------------------------
    # FINAL VALIDATION
    # -----------------------------------

    rag_ids = {
        p["Product_ID"]
        for p in rag_products
    }

    valid_recommendations = [

        p
        for p in recommendations

        if (
            p["Product_ID"]
            in rag_ids
        )

        and (
            p["Product_ID"]
            != detected_product[
                "Product_ID"
            ]
        )
    ]

    return {

        "status":
            "success",

        "yolo": {

            "detections":
                yolo_detections,

            "best_detection":
                yolo_detections[0]
                if yolo_detections
                else None
        },

        "product_detection": {

            "Product_ID":
                detected_product[
                    "Product_ID"
                ],

            "Product_Name":
                detected_product[
                    "Product_Name"
                ],

            "Category":
                detected_product[
                    "Category"
                ],

            "Vision_Score":
                detected_product.get(
                    "score",
                    0
                )
        },

        "vision_top_predictions":
            vision_results,

        "rag_candidates":
            rag_products,

        "recommendations":
            valid_recommendations
    }


